defmodule PuppyLog.Accounts.User.Senders.SendMagicLinkEmail do
  @moduledoc """
  Magic link sender.

  E-mail delivery is not set up yet. Links are generated by hand with
  `mix puppy_log.magic_link` (or `PuppyLog.Accounts.MagicLinks.url_for/2` in
  IEx / a release) and sent via messenger. If someone requests a link through
  the strategy's request endpoint we only log it and send nothing.
  """

  use AshAuthentication.Sender

  require Logger

  @impl true
  def send(user_or_email, _token, _opts) do
    email =
      case user_or_email do
        %{email: email} -> email
        email -> email
      end

    Logger.info("Magic link requested for #{email}; e-mail delivery is disabled.")
    :ok
  end
end
