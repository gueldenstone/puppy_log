defmodule PuppyLog.Accounts.User do
  use Ash.Resource,
    otp_app: :puppy_log,
    domain: PuppyLog.Accounts,
    data_layer: AshSqlite.DataLayer,
    authorizers: [Ash.Policy.Authorizer],
    extensions: [AshAuthentication]

  sqlite do
    table "users"
    repo PuppyLog.Repo
  end

  authentication do
    add_ons do
      log_out_everywhere do
        apply_on_password_change? true
      end
    end

    tokens do
      enabled? true
      token_resource PuppyLog.Accounts.Token
      signing_secret PuppyLog.Secrets
      store_all_tokens? true
      require_token_presence_for_authentication? true
    end

    strategies do
      magic_link do
        identity_field :email
        # Users are created by us (see `mix puppy_log.user.create`), never by sign-up.
        registration_enabled? false
        require_interaction? true
        # Links are generated by hand and sent via messenger, so give them some time.
        token_lifetime {24, :hours}

        sender PuppyLog.Accounts.User.Senders.SendMagicLinkEmail
      end

      # The PWA on the home screen must stay signed in for a long time.
      remember_me :remember_me do
        token_lifetime {365, :days}
      end
    end
  end

  actions do
    defaults [:read]

    create :create do
      description "Creates a household member. Only used from admin tooling."
      accept [:email, :name]
    end

    read :get_by_subject do
      description "Get a user by the subject claim in a JWT"
      argument :subject, :string, allow_nil?: false
      get? true
      prepare AshAuthentication.Preparations.FilterBySubject
    end

    read :get_by_email do
      description "Looks up a user by their email"
      get_by :email
    end

    read :sign_in_with_magic_link do
      description "Sign in an existing user with a magic link."
      get? true

      argument :token, :string do
        description "The token from the magic link"
        allow_nil? false
        sensitive? true
      end

      argument :remember_me, :boolean do
        description "Whether to generate a remember me token"
        allow_nil? true
      end

      prepare AshAuthentication.Strategy.MagicLink.SignInPreparation

      prepare {AshAuthentication.Strategy.RememberMe.MaybeGenerateTokenPreparation,
               strategy_name: :remember_me}

      metadata :token, :string do
        allow_nil? false
      end

      metadata :remember_me, :map do
        allow_nil? true
      end
    end

    action :request_magic_link do
      argument :email, :ci_string do
        allow_nil? false
      end

      run AshAuthentication.Strategy.MagicLink.Request
    end
  end

  policies do
    bypass AshAuthentication.Checks.AshAuthenticationInteraction do
      authorize_if always()
    end

    # One household: every member may see every other member.
    policy action_type(:read) do
      authorize_if actor_present()
    end
  end

  attributes do
    uuid_primary_key :id

    attribute :email, :ci_string do
      allow_nil? false
      public? true
    end

    attribute :name, :string do
      description "Display name, e.g. shown next to entries someone made"
      public? true
    end
  end

  identities do
    identity :unique_email, [:email]
  end
end
